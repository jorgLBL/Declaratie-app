// Drives the app in a phone-sized Chromium with the fake runtime and saves screenshots.
(async () => {
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const here = __dirname;
const out = process.argv[2] || path.join(here, 'shots');
const scheme = process.argv[3] || 'light';
fs.mkdirSync(out, { recursive: true });
const page_src = fs.readFileSync(path.join(here, '../app/declaratie-app.html'), 'utf8');
const mock = fs.readFileSync(path.join(here, 'mock.js'), 'utf8');
const html = `<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style><script>${mock}</script></head><body>${page_src}</body></html>`;
fs.writeFileSync(path.join(out, 'page.html'), html);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' }).catch(() => chromium.launch());
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: scheme, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const jspdfLocal = process.env.JSPDF;
if (jspdfLocal) await page.route('**/jspdf.umd.min.js', r => r.fulfill({ path: jspdfLocal, contentType: 'text/javascript' }));
const errors = [];
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text()); });
page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
await page.goto('file://' + path.join(out, 'page.html'));
await page.waitForTimeout(800);
const shot = async n => page.screenshot({ path: path.join(out, `${n}-${scheme}.png`) });
await shot('01-empty');
// settings
await page.click('#setupGo');
await page.fill('#sName', 'Jorg van Gerner');
await page.fill('#sEmail', 'administratie@bedrijf.nl');
await page.fill('#sIban', 'NL91ABNA0417164300');
await page.click('#calTest'); await page.waitForTimeout(500);
await shot('02-settings');
await page.click('#setDone'); await page.waitForTimeout(200);
// scan
await page.setInputFiles('#camInput', path.join(here, 'receipt.jpg'));
await page.waitForTimeout(300);
await shot('03-reading');
await page.waitForTimeout(1500);
await shot('04-read');
await page.evaluate(() => document.querySelector('#editor').scrollTo(0, 400)); await page.waitForTimeout(100);
await shot('05-read-scrolled');
await page.click('#edDeclare'); await page.waitForTimeout(800);
await shot('06-send');
await page.evaluate(() => document.querySelector('.sheet').scrollTo(0, 2000)); await page.waitForTimeout(100);
await shot('07-send-bottom');
await page.click('#sendShare'); await page.waitForTimeout(400);
await shot('08-after-share');
await page.click('#sendNotYet');
await page.click('#sendClose');
// second receipt on another date with 2 projects
await page.evaluate(() => { window.__sampleAnswer = { total: 41.8, date: '2026-10-09', merchant: 'Q-Park', description: 'Parkeren', category: 'Parkeren', readable: true }; });
await page.setInputFiles('#camInput', path.join(here, 'receipt.jpg'));
await page.waitForTimeout(2000);
await page.evaluate(() => document.querySelector('#editor').scrollTo(0, 400)); await page.waitForTimeout(100);
await shot('09-two-projects');
await page.click('#projAgenda .pchip >> nth=0');
await page.click('#edSave'); await page.waitForTimeout(500);
// third: unreadable
await page.evaluate(() => { window.__sampleAnswer = { readable: false }; });
await page.setInputFiles('#libInput', path.join(here, 'receipt.jpg'));
await page.waitForTimeout(1500);
await shot('10-unreadable');
await page.click('#edCancel');
await page.waitForTimeout(300);
await shot('11-home');
await page.click('#summary button'); await page.waitForTimeout(2500);
await shot('12-send-all');
await page.evaluate(() => document.querySelector('.sheet').scrollTo(0, 2000));
await shot('13-send-all-bottom');
await page.click('#sendShare'); await page.waitForTimeout(300);
const pdfB64 = await page.evaluate(async () => { const b = window.__lastBlob; const buf = new Uint8Array(await b.arrayBuffer()); let s = ''; for (const x of buf) s += String.fromCharCode(x); return btoa(s); });
fs.writeFileSync(path.join(out, 'declaratie.pdf'), Buffer.from(pdfB64, 'base64'));
await page.click('#sendMark'); await page.waitForTimeout(300);
await shot('14-after-mark');
await page.click('#tabSent'); await page.waitForTimeout(300);
await shot('15-sent');
const body = await page.evaluate(() => document.querySelector('#mBody').value);
const state = await page.evaluate(() => ({ saved: window.__saved, calls: window.__calls.filter(c => c.tool).map(c => c.tool + ' ' + (c.input && c.input.startTime)), keys: [...window.__store.keys()] }));
console.log(JSON.stringify(state, null, 1));
console.log('--- body ---\n' + body);
console.log('--- errors ---\n' + errors.join('\n'));
await browser.close();
})();
